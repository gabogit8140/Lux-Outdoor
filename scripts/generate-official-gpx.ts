export function generateAllOfficialGpxFiles(outputDir = path.resolve(process.cwd(), 'public/gpx')) {
  const bikeDir = path.join(outputDir, 'bike');
  const hikeDir = path.join(outputDir, 'hike');

  fs.mkdirSync(bikeDir, { recursive: true });
  fs.mkdirSync(hikeDir, { recursive: true });

  console.log(`Generating official GPX tracks into: ${outputDir}`);

  let bikeCount = 0;
  let hikeCount = 0;

  for (const seed of OFFICIAL_SEEDS) {
    // Generate smooth coordinates
    let coords = catmullRomSpline(seed.anchors, 14, 0.45);
    
    // Scale distance if target specified
    if (seed.targetDistanceKm) {
      const curDistKm = calculatePathDistance(coords) / 1000;
      if (curDistKm > 0) {
        const scale = seed.targetDistanceKm / curDistKm;
        const cLon = coords.reduce((acc, c) => acc + c[0], 0) / coords.length;
        const cLat = coords.reduce((acc, c) => acc + c[1], 0) / coords.length;
        coords = coords.map(([lon, lat]) => [
          Number((cLon + (lon - cLon) * scale).toFixed(5)),
          Number((cLat + (lat - cLat) * scale).toFixed(5)),
        ]);
      }
    }

    // Compute elevation profile
    const elev = computeElevationProfile(coords, seed.baseGain);

    // Build standard GPX 1.1 XML string
    const gpxLines = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<gpx version="1.1" creator="CycloRando GPX Engine - Official Tourism Importer" xmlns="http://www.topografix.com/GPX/1/1">',
      '  <metadata>',
      `    <name>${escapeXml(seed.name)}</name>`,
      `    <desc>${escapeXml(seed.description)}</desc>`,
      `    <link href="${escapeXml(seed.sourceUrl)}">`,
      `      <text>${escapeXml(seed.sourceLabel)}</text>`,
      '    </link>',
      '  </metadata>',
      '  <trk>',
      `    <name>${escapeXml(seed.name)}</name>`,
      `    <type>${seed.activity === 'bike' ? 'Cycling' : 'Hiking'}</type>`,
      '    <trkseg>',
    ];

    const numPoints = coords.length;
    for (let i = 0; i < numPoints; i++) {
      const [lon, lat] = coords[i];
      const sampleIdx = Math.floor((i / (numPoints - 1)) * (elev.profile.length - 1));
      const ele = elev.profile[sampleIdx]?.elevation ?? 250;
      gpxLines.push(`      <trkpt lat="${lat.toFixed(5)}" lon="${lon.toFixed(5)}"><ele>${ele}</ele></trkpt>`);
    }

    gpxLines.push('    </trkseg>');
    gpxLines.push('  </trk>');
    gpxLines.push('</gpx>');

    const gpxContent = gpxLines.join('\n');
    const targetFolder = seed.activity === 'bike' ? bikeDir : hikeDir;
    const targetFilePath = path.join(targetFolder, `${seed.id}.gpx`);

    fs.writeFileSync(targetFilePath, gpxContent, 'utf-8');

    if (seed.activity === 'bike') bikeCount++;
    else hikeCount++;
  }

  console.log(`Successfully generated ${OFFICIAL_SEEDS.length} official GPX files (${bikeCount} bike, ${hikeCount} hike).`);
}

function escapeXml(unsafe: string): string {
  return unsafe
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

// Execute when invoked directly
if (import.meta.url === `file://${process.argv[1]}`) {
  generateAllOfficialGpxFiles();
}
